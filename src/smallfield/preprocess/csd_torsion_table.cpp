/**
 *  @file   src/smallfield/preprocess/csd_torsion_table.cpp
 *  @brief  The CSD torsion-preference corpus as a flat table: 470 SMARTS patterns, six Fourier terms each.
 *
 *  365 rows come from `torsionPreferences_v2.in` and 105 from `torsionPreferences_smallrings.in`, verified
 *  identical to RDKit master row for row.
 *
 *  Row order is @b semantic: `extract_etk_torsions_native` gives a bond to the first pattern that claims
 *  it and the corpus is ordered most-specific first, so sorting or regrouping these rows changes the
 *  conformers the pipeline generates while everything still compiles. Regenerated by:
 *
 *  @code{.py}
 *  # RDKit ships these as C++ fragments, not data: an assignment, one escaped literal per row, a
 *  # block-comment citation header, and `//` notes between rows. Only a row starts with a quote,
 *  # so telling them apart needs no comment stripping.
 *  import pathlib
 *
 *  crystalff = pathlib.Path("rdkit/Code/GraphMol/ForceFieldHelpers/CrystalFF")
 *  for name in ("torsionPreferences_v2", "torsionPreferences_smallrings"):
 *      text = (crystalff / f"{name}.in").read_text()
 *      for line in (raw.strip() for raw in text.splitlines()):
 *          if line.startswith("//"):
 *              note = line.lstrip("/").strip()
 *              if set(note) - set("-=*_ "):  # a run of dashes is a separator, not information
 *                  print(f"    // {note}")
 *          elif line.startswith('"'):
 *              smarts, *terms = line[1 : line.rindex('"')][:-2].split()
 *              signs = ", ".join(terms[0::2])
 *              magnitudes = ", ".join(f"{value}f" for value in terms[1::2])
 *              print(f'    {{"{smarts}", {{{signs}}}, {{{magnitudes}}}}},')
 *  @endcode
 */

